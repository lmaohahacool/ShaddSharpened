    /// <summary>Advance width in pixels: glyphs are 8 wide with a 1px gap baked in,
    /// so text advances 8px per character.</summary>
    public const int ADVANCE = GLYPH_W;

    public static int Measure(string s, int scale = 1)
        => string.IsNullOrEmpty(s) ? 0 : s.Length * ADVANCE * scale;

    /// <summary>Rows of the glyph for <paramref name="c"/>, MSB = leftmost pixel.
    /// Unknown characters render as a solid block so missing glyphs are visible
    /// rather than silently blank.</summary>
    public static void GetGlyph(char c, Span<byte> rows)
    {
        if (rows.Length < GLYPH_H) return;
        if (c < FIRST_CHAR || c > LAST_CHAR) c = (char)127; // DEL is not in the table
        if (c > LAST_CHAR)
        {
            for (int i = 0; i < GLYPH_H; i++) rows[i] = 0xFF;
            return;
        }
        int o = (c - FIRST_CHAR) * GLYPH_H;
        for (int i = 0; i < GLYPH_H; i++) rows[i] = Glyphs[o + i];
    }
